data = json.loads(PATH.read_text(encoding="utf-8"))

# 1) 现有条目标记清音
for k in data["kana"]:
    k["group"] = "seion"

# 2) 追加新条目，沿用现有 id 风格
next_id = max(int(k["id"][1:]) for k in data["kana"]) + 1
for group, rows in [("dakuon", DAKUON), ("youon", YOUON)]:
    for h, k, r, ex, zh in rows:
        if zh is None:  # 示例词太生僻的，换成常见词
            fallback = {
                ("ぞ", "きょうぞ"): ("ぞう", "大象"),
                ("にょ", "にょう"): ("にょうぼう", "嫂子"),
                ("みょ", "みょうにち"): ("みょうじ", "姓氏"),
                ("びゃ", "びゃくやく"): ("びゃくしゃ", "白发"),
            }[("ぞ" if h == "ぞ" else h, ex)]
            ex, zh = fallback
        data["kana"].append({
            "id": f"k{next_id:03d}", "h": h, "k": k, "r": r, "group": group,
            "exJa": ex, "exZh": zh,
        })
        next_id += 1

data["version"] = 2
PATH.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")

counts = {}
for k in data["kana"]:
    counts[k["group"]] = counts.get(k["group"], 0) + 1
