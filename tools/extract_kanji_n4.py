def curated_lookup() -> dict[str, tuple[str, list[str], list[str]]]:
    table: dict[str, tuple[str, list[str], list[str]]] = {}
    table.update(CURATED_N5)
    table.update(CURATED_N4)
    return table


def main() -> int:
    existing = json.loads(OUT_ASSETS.read_text(encoding="utf-8"))
    # 重跑可重复：N5 原样保留，N4 每次从词库重算，避免叠条
    n5_items = [k for k in existing["kanji"] if k.get("level") == "N5"]
    existing_chars = {k["char"] for k in n5_items}
    table = curated_lookup()

    words = json.loads(WORDS.read_text(encoding="utf-8"))
    freq: Counter[str] = Counter()
    mapping: dict[str, list[dict]] = {}
    for w in words["words"]:
        if w.get("level") != "N4":
            continue
        for ch in KANJI_RE.findall(w["ja"]):
            if ch in existing_chars:
                continue
            freq[ch] += 1
            mapping.setdefault(ch, []).append(
                {"ja": w["ja"], "kana": w["kana"], "zh": w["zh"], "id": w["id"]}
            )

    missing = sorted(ch for ch, _ in freq.most_common(TARGET_N4) if ch not in table)
    if missing:
        print(f"✗ Top{TARGET_N4} 缺少审定条目 {len(missing)} 个: {''.join(missing)}", file=sys.stderr)
        return 1

    ordered = [ch for ch, _ in freq.most_common(TARGET_N4)]
    n4_items = []
    for i, ch in enumerate(ordered, start=1):
        zh, on, kun = table[ch]
        examples = [
            {"ja": e["ja"], "kana": e["kana"], "zh": e["zh"]}
            for e in mapping[ch][:2]
        ]
        n4_items.append(
            {
                "id": f"kn4_{i:03d}",
                "char": ch,
                "zh": zh,
                "on": on,
                "kun": kun,
                "level": "N4",
                "examples": examples,
            }
        )

    # 首次并入 N4 后固定 version=2；后续同规模重跑不升版本
    version = 2 if n4_items else existing.get("version", 1)
    payload = {
        "version": version,
        "kanji": n5_items + n4_items,
    }
    text = json.dumps(payload, ensure_ascii=False, indent=2) + "\n"
    OUT_ASSETS.write_text(text, encoding="utf-8")
    batch = {"version": payload["version"], "kanji": n4_items}
    OUT_BATCH.write_text(json.dumps(batch, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    n5 = sum(1 for k in payload["kanji"] if k["level"] == "N5")
    n4 = sum(1 for k in payload["kanji"] if k["level"] == "N4")
    print(f"kanji: N5 {n5} + N4 {n4} = {len(payload['kanji'])} 条 (version {payload['version']})")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
