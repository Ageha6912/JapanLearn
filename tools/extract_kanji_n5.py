def extract_n5_kanji_with_examples() -> dict[str, list[dict]]:
    words = json.loads(WORDS.read_text(encoding="utf-8"))
    n5 = [w for w in words["words"] if w.get("level", "N5") == "N5"]
    mapping: dict[str, list[dict]] = {}
    for w in n5:
        for ch in KANJI_RE.findall(w["ja"]):
            mapping.setdefault(ch, []).append(
                {"ja": w["ja"], "kana": w["kana"], "zh": w["zh"], "id": w["id"]}
            )
    return mapping


def main() -> int:
    mapping = extract_n5_kanji_with_examples()
    missing = sorted(ch for ch in mapping if ch not in CURATED)
    if missing:
        print(f"✗ 缺少审定条目 {len(missing)} 个: {''.join(missing)}", file=sys.stderr)
        return 1

    # 只保留词库中真实出现、且在审定表内的字，按词库首次出现顺序
    ordered: list[str] = []
    seen: set[str] = set()
    words = json.loads(WORDS.read_text(encoding="utf-8"))
    for w in words["words"]:
        if w.get("level", "N5") != "N5":
            continue
        for ch in KANJI_RE.findall(w["ja"]):
            if ch in CURATED and ch not in seen:
                seen.add(ch)
                ordered.append(ch)

    kanji = []
    for i, ch in enumerate(ordered, start=1):
        zh, on, kun = CURATED[ch]
        examples = [
            {"ja": e["ja"], "kana": e["kana"], "zh": e["zh"]}
            for e in mapping[ch][:2]
        ]
        kanji.append(
            {
                "id": f"k{i:03d}",
                "char": ch,
                "zh": zh,
                "on": on,
                "kun": kun,
                "level": "N5",
                "examples": examples,
            }
        )

    payload = {"version": 1, "kanji": kanji}
    text = json.dumps(payload, ensure_ascii=False, indent=2) + "\n"
    OUT_ASSETS.write_text(text, encoding="utf-8")
    OUT_BATCH.write_text(text, encoding="utf-8")
    print(f"kanji: {len(kanji)} 条 → {OUT_ASSETS.name} / {OUT_BATCH.name}")
    return 0


